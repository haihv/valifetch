/**
 * Rewrites site-relative Markdown links (`](/guide/hooks#x)`) in the generated
 * agent files to absolute links to the page's Markdown twin. Without this an
 * agent resolves them against the origin and drops the `/valifetch/` base.
 */
function absolutizeAgentLinks(outDir: string): void {
  const files = readdirSync(outDir, { recursive: true, encoding: 'utf8' })
    .filter((file) => file.endsWith('.md') || file.endsWith('.txt'))
    .map((file) => path.join(outDir, file));
  for (const file of files) {
    const text = readFileSync(file, 'utf8');
    const rewritten = text.replace(
      /\]\(\/(?!\/)([^)\s#]*)(#[^)\s]*)?\)/g,
      (_, target: string, hash = '') => {
        const page = target.replace(/\/$/, '');
        const twin =
          page === '' || /\.[a-z]+$/i.test(page) ? page : `${page}.md`;
        return `](${siteUrl}${twin}${hash})`;
      }
    );
    if (rewritten !== text) writeFileSync(file, rewritten);
  }
}

/** Builds the absolute URL VitePress serves `relativePath` at (cleanUrls). */
function pageUrl(relativePath: string): string {
  const slug = relativePath
    .replace(/(^|\/)index\.md$/, '$1')
    .replace(/\.md$/, '');
  return `${siteUrl}${slug}`;
}

